const DICTS = { en, lg, nyn, teo };

/** Flatten nested dictionaries into dotted keys once, at module load. */
function flatten(obj, prefix = '', out = {}) {
  Object.keys(obj).forEach((k) => {
    const key = prefix ? `${prefix}.${k}` : k;
    const value = obj[k];
    if (value && typeof value === 'object') flatten(value, key, out);
    else out[key] = value;
  });
  return out;
}

export const STRINGS = Object.keys(DICTS).reduce((acc, code) => {
  acc[code] = flatten(DICTS[code]);
  return acc;
}, {});

export function translate(lang, key) {
  const dict = STRINGS[lang] || STRINGS.en;
  return dict[key] != null ? dict[key] : STRINGS.en[key] != null ? STRINGS.en[key] : key;
}
